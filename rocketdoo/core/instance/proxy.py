"""Install and configure Nginx (+ Let's Encrypt via certbot) in front of a Docker instance.

Manexware fork: replaces the upstream Traefik installer. The compose publishes
Odoo on 127.0.0.1:<host_http_port> and the gevent/websocket worker on
127.0.0.1:<host_gevent_port>; the host's Nginx is what answers on 80/443.

One site file per environment (`rkd-<slug>.conf`), so stage and prod can share
a VPS. Upstream, map and site names carry the slug for the same reason:
nginx refuses two `map` blocks that define the same variable.

`render_site` is pure and tested; `install_script` returns the `bash -s` the
VPS runs; `install` sends it.
"""

import re
import shlex
import subprocess

from rocketdoo.core.service import ProgressCallback, ServiceError, reporter

from .ssh_utils import build_ssh_cmd

SITES_AVAILABLE = "/etc/nginx/sites-available"
SITES_ENABLED = "/etc/nginx/sites-enabled"
CONF_D = "/etc/nginx/conf.d"

_TIMEOUT = 900
_SITE_EOF = "RKD_NGINX_SITE"
_DOMAIN = re.compile(r"(?=.{1,253}$)([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]{2,63}")
_SLUG = re.compile(r"[A-Za-z0-9_]+")


class ProxyError(ServiceError):
    pass


def site_name(slug: str) -> str:
    return f"rkd-{slug}.conf"


def render_site(
    *,
    slug: str,
    domain: str,
    http_port: int,
    gevent_port: int,
    max_body: str = "200m",
) -> str:
    """The Nginx server block for one Odoo instance, plain HTTP.

    certbot --nginx adds the 443 server and the redirect to this same file,
    so a first deploy works over HTTP even before DNS points at the VPS.
    Follows Odoo's own deployment guide: websocket to the gevent port,
    X-Forwarded-* for proxy_mode, long timeouts for reports and imports.
    """
    if not _SLUG.fullmatch(slug):
        raise ValueError(f"invalid slug {slug!r}")
    if not _DOMAIN.fullmatch(domain):
        raise ValueError(f"invalid domain {domain!r}")
    up, chat, upgrade = f"rkd_{slug}_odoo", f"rkd_{slug}_chat", f"$rkd_{slug}_conn_upgrade"
    return f"""# Generated by rkd instance nginx ({slug}) -- Manexware rocketdoo fork.
# Kept on later runs unless --force; certbot edits it to add HTTPS.

upstream {up} {{
    server 127.0.0.1:{int(http_port)};
}}

upstream {chat} {{
    server 127.0.0.1:{int(gevent_port)};
}}

map $http_upgrade {upgrade} {{
    default upgrade;
    ''      close;
}}

server {{
    listen 80;
    listen [::]:80;
    server_name {domain};

    client_max_body_size {max_body};
    proxy_read_timeout 720s;
    proxy_connect_timeout 720s;
    proxy_send_timeout 720s;

    access_log /var/log/nginx/rkd-{slug}.access.log;
    error_log /var/log/nginx/rkd-{slug}.error.log;

    location /websocket {{
        proxy_pass http://{chat};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection {upgrade};
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Real-IP $remote_addr;
    }}

    location / {{
        proxy_pass http://{up};
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_redirect off;
    }}

    location ~* /web/static/ {{
        proxy_cache_valid 200 90m;
        expires 864000;
        proxy_pass http://{up};
    }}

    gzip on;
    gzip_types text/css text/scss text/plain text/xml application/xml application/json application/javascript;
}}
"""


def install_script(
    *,
    slug: str,
    domain: str,
    email: str,
    http_port: int,
    gevent_port: int,
    force: bool = False,
    certbot: bool = True,
) -> str:
    """The `bash -s` that installs Nginx/certbot if needed, writes the site and gets the certificate.

    Prints key=value facts on stdout for `_parse`. Needs root or passwordless
    sudo: it touches /etc/nginx and apt.
    """
    if certbot and (not email or any(c in email for c in "\n\r'\" ;$`") or "@" not in email):
        raise ValueError("The Let's Encrypt email must be a plain single-line address")
    site = render_site(slug=slug, domain=domain, http_port=http_port, gevent_port=gevent_port)
    name = site_name(slug)
    q_domain = shlex.quote(domain)
    lines = [
        "{",
        "set -u",
        'if [ "$(id -u)" = 0 ]; then SUDO=""; elif sudo -n true 2>/dev/null; then SUDO="sudo -n"; else',
        "  echo 'The SSH user needs root or passwordless sudo to configure Nginx' >&2; exit 1; fi",
        # Something other than nginx on 80/443 (a leftover Traefik, Apache) would
        # make nginx fail to bind: say so instead of half-configuring.
        "busy=$( ($SUDO ss -ltnp 2>/dev/null || true) | awk '$4 ~ /:(80|443)$/' | grep -v nginx | head -1)",
        'if [ -n "$busy" ]; then echo "ports_taken=$busy"; echo done=yes; exit 0; fi',
        "installed=no",
        "if ! command -v nginx >/dev/null 2>&1; then",
        "  if ! command -v apt-get >/dev/null 2>&1; then echo 'Only Debian/Ubuntu (apt) is supported for the automatic install' >&2; exit 1; fi",
        "  $SUDO env DEBIAN_FRONTEND=noninteractive apt-get update -qq >&2",
        "  $SUDO env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nginx >&2 || exit 1",
        "  installed=yes",
        "fi",
        'echo "nginx_installed=$installed"',
    ]
    if certbot:
        lines += [
            "if ! command -v certbot >/dev/null 2>&1; then",
            "  $SUDO env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq certbot python3-certbot-nginx >&2"
            " || echo certbot_install=failed",
            "fi",
        ]
    lines += [
        f"if [ -d {SITES_AVAILABLE} ]; then site={SITES_AVAILABLE}/{name}; link={SITES_ENABLED}/{name};"
        f" else site={CONF_D}/{name}; link=''; fi",
        f'if [ -e "$site" ] && [ "{"yes" if force else "no"}" = no ]; then echo site=kept; else',
        f"  $SUDO tee \"$site\" >/dev/null <<'{_SITE_EOF}'",
        site.rstrip("\n"),
        _SITE_EOF,
        "  echo site=written",
        # A VPS with IPv6 disabled makes `listen [::]:80` fatal for nginx.
        '  if ! grep -q . /proc/net/if_inet6 2>/dev/null; then $SUDO sed -i "/listen \\[::\\]:80;/d" "$site"; fi',
        "fi",
        'if [ -n "$link" ]; then $SUDO ln -sf "$site" "$link"; fi',
        'echo "site_path=$site"',
        "if ! $SUDO nginx -t >&2; then echo nginx_test=failed; echo done=yes; exit 0; fi",
        "$SUDO systemctl enable --now nginx >/dev/null 2>&1 || true",
        "if $SUDO systemctl reload nginx >&2 || $SUDO nginx -s reload >&2; then echo reloaded=yes; else echo reloaded=no; fi",
    ]
    if certbot:
        lines += [
            f"if $SUDO test -d /etc/letsencrypt/live/{q_domain}; then",
            "  echo cert=present",
            # Re-attach the existing certificate in case the site was rewritten (--force).
            f"  $SUDO certbot --nginx -d {q_domain} --non-interactive --reinstall --redirect >&2 || true",
            "elif command -v certbot >/dev/null 2>&1; then",
            f"  if $SUDO certbot --nginx -d {q_domain} -m {shlex.quote(email)} --agree-tos --no-eff-email"
            " --non-interactive --redirect >&2; then echo cert=issued; else echo cert=failed; fi",
            "else echo cert=no_certbot; fi",
        ]
    else:
        lines.append("echo cert=skipped")
    lines += ["echo done=yes", "}"]
    return "\n".join(lines) + "\n"


def _parse(output: str) -> dict:
    facts = {}
    for line in output.splitlines():
        key, sep, value = line.partition("=")
        if sep:
            facts[key] = value.strip()
    return facts


def install(
    auth: dict,
    vps: dict,
    *,
    slug: str,
    domain: str,
    email: str,
    http_port: int,
    gevent_port: int,
    force: bool = False,
    certbot: bool = True,
    on_progress: ProgressCallback | None = None,
) -> dict:
    progress = reporter(on_progress)
    script = install_script(
        slug=slug,
        domain=domain,
        email=email,
        http_port=http_port,
        gevent_port=gevent_port,
        force=force,
        certbot=certbot,
    )
    cmd, env = build_ssh_cmd(auth, vps.get("port", 22), vps["user"], vps["host"], "bash -s")
    progress(f"Configuring Nginx for {domain} on {vps['host']}", "info")
    try:
        result = subprocess.run(cmd, input=script, capture_output=True, text=True, timeout=_TIMEOUT, env=env)
    except (subprocess.SubprocessError, OSError) as error:
        raise ProxyError(f"Could not reach {vps['host']}: {error}") from error
    if result.returncode != 0:
        reason = (result.stderr or "").strip().splitlines()[-1:] or [f"ssh exited {result.returncode}"]
        raise ProxyError(f"The Nginx setup failed on {vps['host']}: {reason[0]}")
    facts = _parse(result.stdout)
    if facts.get("done") != "yes":
        raise ProxyError("The VPS answered but the setup ended before it finished")
    return {
        "ports_taken": facts.get("ports_taken", ""),
        "nginx_installed": facts.get("nginx_installed") == "yes",
        "site": facts.get("site", ""),
        "site_path": facts.get("site_path", ""),
        "nginx_test_failed": facts.get("nginx_test") == "failed",
        "reloaded": facts.get("reloaded") == "yes",
        "cert": facts.get("cert", ""),
        "stderr_tail": "\n".join((result.stderr or "").strip().splitlines()[-15:]),
    }
